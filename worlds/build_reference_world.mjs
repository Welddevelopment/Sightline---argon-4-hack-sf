// Regenerates worlds/reference_world.js (WORLD CONTRACT v2: createWorld(THREE, assets)) from case/case.json.
// Usage: node worlds/build_reference_world.mjs
// The world only PLACES library assets (web/assets.js); motion = linear interpolation of case.json keyframes (0.25 s apart).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const c = JSON.parse(fs.readFileSync(path.join(here, '../case/case.json'), 'utf8'));
const veh = Object.fromEntries(c.vehicles.map((v) => [v.id, v]));
// Start-early rule: Vehicle A's path must begin before the crest (>= 345 m from impact, NTSB p.29). case.json puts the car's
// front exactly AT the crest at t=0 (345.03 m), so the constant-speed pre-impact segment is stretched to start 2.5 m earlier
// (+0.5 mph, inside the recorder's 74 mph rounding). Post-impact keyframes are unchanged.
{
  const K = veh.veh_A.keyframes, tI = c.timeline.t_impact;
  const i = K.findIndex((k) => k.t >= tI), a = K[i - 1], b = K[i], u = (tI - a.t) / (b.t - a.t);
  const xI = a.x + (b.x - a.x) * u, zI = a.z + (b.z - a.z) * u, x0 = K[0].x, x0new = x0 - 2.5, f = (xI - x0new) / (xI - x0);
  veh.veh_A.keyframes = [...K.filter((k) => k.t < tI).map((k) => ({ ...k, x: Math.round((xI + (k.x - xI) * f) * 100) / 100 })), { t: tI, x: Math.round(xI * 100) / 100, z: Math.round(zI * 100) / 100, heading_deg: a.heading_deg + (b.heading_deg - a.heading_deg) * u }, ...K.filter((k) => k.t > tI)];
}
const kf = (id) => '[' + veh[id].keyframes.map((k) => `[${k.t},${k.x},${k.z},${k.heading_deg}]`).join(',') + ']';
const occ = Object.fromEntries(c.occluders.map((o) => [o.id, o]));
const kd = c.key_dimensions;
// Citations that admit an assumption carry the "inferred" label (validator rule).
const cite = (s) => (/inferred/i.test(s) || !/\b(assum\w*|typical|estimate\w*|derived|fictionali[sz]ed|approximat\w*|simplified)\b/i.test(s) ? s : 'inferred: ' + s);
const J = (s) => JSON.stringify(s);
const C = (s) => J(cite(s));

const witOverride = JSON.parse(fs.existsSync(path.join(here, 'witness_overrides.json')) ? fs.readFileSync(path.join(here, 'witness_overrides.json'), 'utf8') : '{}');
const witnesses = c.witnesses.map((w) => {
  const o = witOverride[w.id] || {};
  const p = o.position || w.marked_position || w.position;
  return {
    id: w.id, name: w.name, position: [p[0], 0, p[2]], eyeHeight: w.eyeHeight, lookAt: o.lookAt || w.lookAt,
    observationTime: o.observationTime ?? w.observationTime_s ?? w.observationTime, claim: w.claim, citation: cite(w.citation),
    ...(o.note ? { note: o.note } : {}),
  };
});
const facts = [
  { id: 'f_impact_t', text: `Impact at t=${c.timeline.t_impact} s on the event clock (car crests the hill at t=0)`, value: c.timeline.t_impact, unit: 's', citation: 'NTSB/HAR-17/02 p.22, p.29 (derived from 74 mph over 345 m)', kind: 'time' },
  ...c.facts,
].map((f) => ({ ...f, citation: cite(f.citation) }));

// Case time/place for the sun (NTSB/HAR-17/02 p.1, p.5: 4:36:12 p.m. EDT, 7 May 2016, US-27A at NE 140th Ct, Williston FL).
const loc = { iso: '2016-05-07T16:36:12-04:00', date: '2016-05-07', time: (c.timeline.clock_at_impact || c.timeOfDay).replace(/\.\d+$/, ''), utcOffset: '-04:00', timeZone: 'America/New_York',
  lat: 29.4106, lon: -82.5393 };
const FT = 0.3048;
const r2 = (x) => Math.round(x * 100) / 100;
const sr = kd.side_road;
const medW = kd.turnlane_median_shoulders_total_m;                               // EB inside edge -> WB inside edge (78 ft)
const zC = r2(kd.eb_inside_lane_z[0] - medW / 2);                                 // highway centreline
const crestX = kd.crest_x_m;
const CREST_CURVE = 140, DOWN_LEN = 235;                                          // grade ends 40 m west of the crossover (see header)
const crestH = r2(0.0215 * DOWN_LEN);
const turnStopS = -100 + kd.median_crossover_length_m / 2;
const rp = kd.pole_position_approx;
const polesX = []; for (let x = rp[0] - 46 * 20; x <= 760; x += 46) if ((x < -15 || x > 40) && Math.abs(x - rp[0]) > 1) polesX.push(r2(x));

const src = `// Sightline reference world: ${c.title}
// GENERATED by worlds/build_reference_world.mjs from case/case.json. WORLD CONTRACT v2: places library assets only (createWorld(THREE, assets)).
// ${c.source_note}
// Frame: meters, Y up, +X east (direction of Vehicle A), -Z north. Origin = initial point of impact (center of EB outside lane at NE 140th Ct).
// Terrain: vertical crest ${-crestX} m west (NTSB/HAR-17/02 p.22-23), 2.15% down-grade toward the crossover. Modeling simplification: the
// grade levels out ${-crestX - DOWN_LEN - CREST_CURVE / 2} m west of the crossover (crest ${crestH} m above the crossover instead of ~7.4 m) so the witness/impact
// area is level (y=0) for the ray-cast checks. Tree lines, fences and the utility-pole line are illustrative scenery (not occluders, not from the record).
// Lighting: sun/sky/fog from the library's solar model for ${loc.iso} at ${loc.lat}, ${loc.lon} (NTSB/HAR-17/02 p.1, p.5: 4:36 p.m. EDT, clear).
export default function createWorld(THREE, assets) {
  const root = new THREE.Group();
  root.name = 'world_root';
  const objects = {};
  const D2R = Math.PI / 180;
  const T = assets.terrain || { reset() {}, hillCrest() {}, height: () => 0, roadHeight: () => 0 };
  T.reset();
  const gy = (x, z) => T.height(x, z);
  // place a library asset: ground-level origin at (x, z), compass heading in degrees (rotation.y = -heading)
  const add = (id, node, kind, label, citation, occludes, x = 0, z = 0, headingDeg = 0, extra = {}) => {
    node.name = id; node.position.set(x, gy(x, z), z); node.rotation.y = -headingDeg * D2R; root.add(node);
    return (objects[id] = { node, kind, label, citation, occludes, ...extra });
  };
  const reg = (id, node, kind, label, citation, occludes = false) => { node.name = id; root.add(node); return (objects[id] = { node, kind, label, citation, occludes }); };
  const scenery = (node) => { node.userData.scenery = true; root.add(node); return node; };

  // ---------- light: the library's physically based sun / sky / fog for the case's date, time and place ----------
  root.add(assets.environment({ date: ${J(loc.iso)}, lat: ${loc.lat}, lon: ${loc.lon}, weather: 'clear' }));

  // ---------- terrain: vertical crest west of the crossover (roads drape onto it) ----------
  T.hillCrest({ at: [${crestX}, ${zC}], heading: -Math.PI / 2, gradeUp: 0.02, lengthUp: 400, gradeDown: 0.0215, lengthDown: ${DOWN_LEN}, curve: ${CREST_CURVE} });

  // ---------- roadway: US-27A four-lane divided (3.66 m lanes), 39.6 m crossover, WB left-turn lane, NE 140th Ct ----------
  reg('road_us27a', assets.road({ id: 'road_us27a', lanes: 4, laneWidth: ${kd.lane_width_m}, divided: true, medianWidth: ${r2(medW)}, length: 1700, markings: 'standard',
    shoulderWidth: ${r2(5 * FT)}, leftShoulderWidth: ${r2(2 * FT)}, position: [100, ${zC}], heading: -Math.PI / 2,
    openings: [{ at: -100, width: ${kd.median_crossover_length_m}, radius: 6 }],
    turnLanes: [{ carriageway: 'reverse', stopAt: ${r2(turnStopS)}, length: ${r2(kd.wb_left_turn_lane_length_m - 15)}, taper: 15 }],
    sideRoads: [{ at: -100, side: 'right', width: ${sr.width_m}, radius: 9 }] }),
    'road', 'US-27A: 4-lane divided highway, 3.66 m lanes, 18.3 m grass median, 39.6 m crossover, WB left-turn lane (65 mph)', 'NTSB/HAR-17/02 p.22-23', false);
  const outer = objects.road_us27a.node.userData.edges?.outer ?? ${r2(medW / 2 + 2 * kd.lane_width_m + 5 * FT)};
  const sideStart = ${zC} + outer;
  reg('road_ne140', assets.road({ id: 'road_ne140', lanes: 2, laneWidth: ${r2(sr.width_m / 2)}, shoulderWidth: 0, markings: 'center_double', edgeLines: false, length: 260,
    position: [0, sideStart + 130], heading: 0, rpms: false, roadside: { ditchDepth: 0.35 } }),
    'road', 'NE 140th Court (runs south; 109 deg skew simplified)', ${C('NTSB/HAR-17/02 p.1, p.22; width assumed')}, false);

  // ---------- ground + illustrative scenery (pasture, hammock tree lines, fences, pole line) ----------
  root.add(assets.groundPlane({ id: 'ground', size: 4000, kind: 'pasture' }));
  scenery(assets.treeline({ id: 'scn_trees_n', points: [[-900, -170], [-400, -190], [0, -160], [500, -185], [900, -175]], depth: 22, spacing: 8, seed: 3 }));
  scenery(assets.treeline({ id: 'scn_trees_s', points: [[-900, 150], [-300, 170], [60, 95], [400, 140], [900, 160]], depth: 26, spacing: 8, seed: 5, pineRatio: 0.45 }));
  scenery(assets.treeline({ id: 'scn_trees_s2', points: [[-260, 60], [-180, 64]], depth: 10, spacing: 7, seed: 9, height: 11 }));
  for (const [id, z, segs] of [['scn_fence_n', ${r2(zC - 36)}, [[-800, 800]]], ['scn_fence_s', 12.5, [[-800, -14], [40, 800]]]])
    for (const [a, b] of segs) { const pts = []; for (let x = a; x <= b; x += 50) pts.push([x, z]); if (pts[pts.length - 1][0] < b) pts.push([b, z]); scenery(assets.fence({ id: id + '_' + a, points: pts })); }
  for (const x of ${JSON.stringify(polesX)}) { const p = scenery(assets.pole({ id: 'scn_pole_' + x, height: 10.7 })); p.position.set(x, gy(x, ${rp[1]}), ${rp[1]}); }
  for (const [x, z, h, k] of [[34, 30, 10, 'oak'], [-22, 26, 12, 'oak'], [-40, 40, 18, 'pine'], [60, -64, 9, 'oak'], [-120, 52, 17, 'pine'], [140, 48, 10, 'oak'], [-70, -70, 11, 'oak']]) {
    const tr = scenery(assets.tree({ id: 'scn_tree_' + x, kind: k, height: h })); tr.position.set(x, gy(x, z), z); tr.rotation.y = x;
  }

  // ---------- evidence objects / occluders ----------
  const crest = new THREE.Group();
  const crestBox = new THREE.Mesh(new THREE.BoxGeometry(60, 0.2, 40), new THREE.MeshBasicMaterial({ visible: false }));
  crestBox.visible = false; crestBox.position.set(-30, 0, 0); crest.add(crestBox);
  crest.position.set(${crestX}, ${crestH}, ${zC});
  reg('occ_crest', crest, 'terrain', 'Vertical crest of US-27A, ${-crestX} m west (sight restriction; rendered as terrain)', ${C(occ.occ_crest.citation)}, false);
  add('bld_store', assets.building({ id: 'bld_store', w: 18, d: 12, h: ${occ.bld_store.height}, kind: 'store' }), 'building', ${J(occ.bld_store.label)}, ${C(occ.bld_store.citation)}, true, ${occ.bld_store.position[0]}, ${occ.bld_store.position[2]});
  add('occ_shelter', assets.shelter({ id: 'occ_shelter', open: true }), 'occluder', ${J(occ.occ_shelter.label)}, ${C(occ.occ_shelter.citation)}, false, ${occ.occ_shelter.position[0]}, ${occ.occ_shelter.position[2]});
  add('occ_pole', assets.pole({ id: 'occ_pole', height: 10.7 }), 'occluder', 'Utility pole broken by Vehicle A (position derived)', ${C('NTSB/HAR-17/02 p.1; ' + kd.pole_note)}, true, ${rp[0]}, ${rp[1]});

  // ---------- marks ----------
  add('mark_impact', assets.impactMarker({ id: 'mark_impact', position: [0, 0] }), 'mark', 'Initial point of impact (EB outside lane at NE 140th Ct)', 'NTSB/HAR-17/02 p.1, p.5', false, 0, 0);
  add('mark_rest_A', assets.impactMarker({ id: 'mark_rest_A', position: [${kd.car_rest_position_approx[0]}, ${kd.car_rest_position_approx[1]}] }), 'mark', 'Final rest of Vehicle A (~910 ft past impact)', ${C('NTSB/HAR-17/02 p.1; position approximate')}, false, ${kd.car_rest_position_approx[0]}, ${kd.car_rest_position_approx[1]});
  const KA = ${kf('veh_A')};
  const pathPts = KA.filter((k) => k[0] > ${c.timeline.t_impact}).map((k) => [k[1], k[2]]);
  const pathMark = assets.skidMark({ id: 'mark_path_A', points: pathPts, width: 0.3 });
  reg('mark_path_A', pathMark, 'mark', 'Post-impact path of Vehicle A (no pre-impact tire marks)', 'NTSB/HAR-17/02 p.1, p.5', false);

  // ---------- vehicles (library assets; front = local -Z) ----------
  const A = add('veh_A', assets.vehicle('sedan', { id: 'veh_A', color: '#1d2c44' }), 'vehicle', ${J(veh.veh_A.label)}, ${C(veh.veh_A.citation)}, true).node;
  const TT = add('veh_T_tractor', assets.vehicle('truck_tractor', { id: 'veh_T_tractor', color: '#e8e8e8' }), 'vehicle', ${J(veh.veh_T_tractor.label)}, ${C(veh.veh_T_tractor.citation)}, true).node;
  const TR = add('veh_T_trailer', assets.vehicle('semitrailer', { id: 'veh_T_trailer', color: '#f2f2ee' }), 'vehicle', ${J(veh.veh_T_trailer.label)}, ${C(veh.veh_T_trailer.citation)}, true).node;

  // ---------- motion: linear interpolation of case.json keyframes [t, x, z, heading_deg] ----------
  const KT = ${kf('veh_T_tractor')};
  const KR = ${kf('veh_T_trailer')};
  function sample(K, t) {
    if (t <= K[0][0]) return K[0];
    const last = K[K.length - 1];
    if (t >= last[0]) return last;
    let i = 0;
    while (K[i + 1][0] < t) i++;
    const a = K[i], b = K[i + 1], u = (t - a[0]) / (b[0] - a[0]);
    let dh = b[3] - a[3];
    if (dh > 180) dh -= 360;
    if (dh < -180) dh += 360;
    return [t, a[1] + (b[1] - a[1]) * u, a[2] + (b[2] - a[2]) * u, a[3] + dh * u];
  }
  function place(node, K, t) {
    const s = sample(K, t);
    const h = s[3] * D2R, fx = Math.sin(h), fz = -Math.cos(h);           // compass heading -> forward (x east, -z north)
    const y = T.roadHeight(s[1], s[2]);
    const pitch = Math.atan((T.roadHeight(s[1] + fx * 2, s[2] + fz * 2) - T.roadHeight(s[1] - fx * 2, s[2] - fz * 2)) / 4);
    node.position.set(s[1], y, s[2]);
    node.rotation.set(pitch, -h, 0, 'YXZ');
  }

  const T_IMPACT = ${c.timeline.t_impact};
  const duration = ${c.timeline.duration_s};
  function setTime(t) {
    t = Math.min(Math.max(t, 0), duration);
    place(A, KA, t);
    place(TT, KT, t);
    place(TR, KR, t);
    root.updateMatrixWorld(true);
  }

  // ---------- witnesses (FICTIONAL) ----------
  const witnesses = ${JSON.stringify(witnesses, null, 2).replace(/\n/g, '\n  ')};

  const facts = ${JSON.stringify(facts, null, 2).replace(/\n/g, '\n  ')};
  const skids = []; // ${c.skids_note}

  const world = {
    meta: { caseId: ${J(c.caseId)}, title: ${J(c.title)}, timeOfDay: ${J(c.timeOfDay)}, lighting: ${J(c.lighting)}, impactT: T_IMPACT,
      date: ${J(loc.date)}, dateTime: ${J(loc.iso)}, weather: 'clear', timeZone: ${J(loc.timeZone)}, utcOffset: ${J(loc.utcOffset)}, lat: ${loc.lat}, lon: ${loc.lon},
      source: 'NTSB/HAR-17/02 (HWY16FH018) physical facts + fictional witnesses', contract: 'v2' },
    root, duration, setTime, objects, witnesses, facts, skids,
  };
  setTime(0);
  return world;
}
`;
fs.writeFileSync(path.join(here, 'reference_world.js'), src);
console.log('wrote worlds/reference_world.js', src.length, 'bytes');
