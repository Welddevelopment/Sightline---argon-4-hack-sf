// Regenerates worlds/reference_world.js (WORLD CONTRACT v2: createWorld(THREE, assets)) from case/case.json.
// Usage: node worlds/build_reference_world.mjs
// The world only PLACES library assets (web/assets.js); motion = linear interpolation of case.json keyframes (0.25 s apart).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const c = JSON.parse(fs.readFileSync(path.join(here, '../case/case.json'), 'utf8'));
const veh = Object.fromEntries(c.vehicles.map((v) => [v.id, v]));
const kf = (id) => '[' + veh[id].keyframes.map((k) => `[${k.t},${k.x},${k.z},${k.heading_deg}]`).join(',') + ']';
const occ = Object.fromEntries(c.occluders.map((o) => [o.id, o]));
const kd = c.key_dimensions;
// Citations that admit an assumption carry the "inferred" label (validator rule).
const cite = (s) => (/inferred/i.test(s) || !/\b(assum\w*|typical|estimate\w*|derived|fictionali[sz]ed|approximat\w*|simplified)\b/i.test(s) ? s : 'inferred: ' + s);
const J = (s) => JSON.stringify(s);
const C = (s) => J(cite(s));

const witOverride = JSON.parse(fs.existsSync(path.join(here, 'witness_overrides.json')) ? fs.readFileSync(path.join(here, 'witness_overrides.json'), 'utf8') : '{}');
const witnesses = c.witnesses.map((w) => {
  const o = witOverride[w.id] || {};
  const p = o.position || w.marked_position || w.position;
  return {
    id: w.id, name: w.name, position: [p[0], 0, p[2]], eyeHeight: w.eyeHeight, lookAt: o.lookAt || w.lookAt,
    observationTime: o.observationTime ?? w.observationTime_s ?? w.observationTime, claim: w.claim, citation: cite(w.citation),
    ...(o.note ? { note: o.note } : {}),
  };
});
const facts = [
  { id: 'f_impact_t', text: `Impact at t=${c.timeline.t_impact} s on the event clock (car crests the hill at t=0)`, value: c.timeline.t_impact, unit: 's', citation: 'NTSB/HAR-17/02 p.22, p.29 (derived from 74 mph over 345 m)', kind: 'time' },
  ...c.facts,
].map((f) => ({ ...f, citation: cite(f.citation) }));

// Case time/place for the sun (NTSB/HAR-17/02 p.1, p.5: 4:36:12 p.m. EDT, 7 May 2016, US-27A at NE 140th Ct, Williston FL).
const loc = { date: '2016-05-07', time: (c.timeline.clock_at_impact || c.timeOfDay).replace(/\.\d+$/, ''), utcOffset: '-04:00', timeZone: 'America/New_York',
  lat: 29.41, lon: -82.54, ...(c.location || {}) };
const X0 = -440, X1 = 340, XM = (X0 + X1) / 2, XL = X1 - X0;
const ebC = (kd.eb_inside_lane_z[0] + kd.eb_outside_lane_z[1]) / 2;            // EB 2-lane center
const wbC = (kd.wb_outside_lane_z[0] + kd.wb_inside_lane_z[1]) / 2;            // WB 2-lane center
const tl = kd.wb_left_turn_lane_z, med = kd.median_z, sr = kd.side_road;
const medW = med[1] - med[0], medC = (med[0] + med[1]) / 2;
const turnX0 = -19.8, turnX1 = 167.6;
const r2 = (x) => Math.round(x * 100) / 100;

const src = `// Sightline reference world: ${c.title}
// GENERATED by worlds/build_reference_world.mjs from case/case.json. WORLD CONTRACT v2: places library assets only (createWorld(THREE, assets)).
// ${c.source_note}
// Frame: meters, Y up, +X east (direction of Vehicle A), -Z north. Origin = initial point of impact (center of EB outside lane at NE 140th Ct).
// Ground modeled flat (2.15% grade ignored for sightlines); the crest is a terrain proxy (catalog has no terrain asset).
export default function createWorld(THREE, assets) {
  const root = new THREE.Group();
  root.name = 'world_root';
  const objects = {};
  const D2R = Math.PI / 180;
  // place a library asset: ground-level origin at (x, z), compass heading in degrees (rotation.y = -heading)
  const add = (id, node, kind, label, citation, occludes, x = 0, z = 0, headingDeg = 0, extra = {}) => {
    node.name = id; node.position.set(x, 0, z); node.rotation.y = -headingDeg * D2R; root.add(node);
    return (objects[id] = { node, kind, label, citation, occludes, ...extra });
  };

  // ---------- light + ground: ${c.timeOfDay} local (EDT, UTC-4), ${c.weather} ----------
  root.add(assets.environment({ date: ${J(loc.date)}, timeOfDay: ${J(loc.time)}, utcOffset: ${J(loc.utcOffset)}, timeZone: ${J(loc.timeZone)}, lat: ${loc.lat}, lon: ${loc.lon}, lighting: ${J(c.lighting)}, weather: 'clear' }));
  // sun position is computed by the library from date/time/place (NTSB/HAR-17/02 p.1, p.5: 4:36:12 p.m. EDT, clear; US-27A near Williston, FL)
  const ground = assets.groundPlane({ id: 'ground', size: ${XL + 40}, kind: 'grass' });
  ground.position.set(${XM}, 0, 0);
  root.add(ground);

  // ---------- roadway: US-27A four-lane divided (3.66 m lanes), crossover, NE 140th Ct ----------
  add('road_eb', assets.road({ id: 'road_eb', lanes: 2, laneWidth: ${kd.lane_width_m}, length: ${XL}, markings: 'center_dashed', edgeLines: true }), 'road', 'US-27A eastbound (2 x 3.66 m lanes, 65 mph limit)', 'NTSB/HAR-17/02 p.22-23', false, ${XM}, ${r2(ebC)}, 90);
  add('road_wb', assets.road({ id: 'road_wb', lanes: 2, laneWidth: ${kd.lane_width_m}, length: ${XL}, markings: 'center_dashed', edgeLines: true }), 'road', 'US-27A westbound (2 x 3.66 m lanes)', 'NTSB/HAR-17/02 p.22', false, ${XM}, ${r2(wbC)}, 90);
  add('road_wb_turn', assets.road({ id: 'road_wb_turn', lanes: 1, laneWidth: ${kd.lane_width_m}, length: ${r2(turnX1 - turnX0)}, markings: 'none', edgeLines: true }), 'road', 'Westbound left-turn lane (167.6 m)', 'NTSB/HAR-17/02 p.22', false, ${r2((turnX0 + turnX1) / 2)}, ${r2((tl[0] + tl[1]) / 2)}, 90);
  add('road_median_w', assets.median({ id: 'road_median_w', width: ${r2(medW)}, length: ${r2(turnX0 - X0)} }), 'road', 'Grass median (18.29 m) west of the crossover', 'NTSB/HAR-17/02 p.22', false, ${r2((X0 + turnX0) / 2)}, ${r2(medC)}, 90);
  add('road_median_e', assets.median({ id: 'road_median_e', width: ${r2(medW)}, length: ${r2(X1 - 19.8)} }), 'road', 'Grass median (18.29 m) east of the crossover', 'NTSB/HAR-17/02 p.22', false, ${r2((19.8 + X1) / 2)}, ${r2(medC)}, 90);
  for (const [id, x] of [['road_crossover_w', -9.9], ['road_crossover_e', 9.9]]) add(id, assets.intersection({ id, size: 19.8 }), 'road', 'Uncontrolled 39.6 m median crossover (paved)', 'NTSB/HAR-17/02 p.22', false, x, ${r2(medC)});
  add('road_ne140', assets.road({ id: 'road_ne140', lanes: 2, laneWidth: ${r2(sr.width_m / 2)}, length: 146.6, markings: 'none', edgeLines: false }), 'road', 'NE 140th Court (runs south; 109 deg skew simplified)', ${C('NTSB/HAR-17/02 p.1, p.22; width assumed')}, false, 0, 76.7, 0);

  // ---------- static occluders / scenery ----------
  add('occ_crest', assets.building({ id: 'occ_crest', w: 60, d: 80, h: 7.4, kind: 'generic' }), 'occluder', 'Vertical crest of US-27A, 345 m west (terrain proxy: hill mass beyond the crest)', ${C(occ.occ_crest.citation + '; approximated as a solid block')}, true, ${kd.crest_x_m - 32}, -15);
  add('bld_store', assets.building({ id: 'bld_store', w: 18, d: 12, h: ${occ.bld_store.height}, kind: 'store' }), 'building', ${J(occ.bld_store.label)}, ${C(occ.bld_store.citation)}, true, ${occ.bld_store.position[0]}, ${occ.bld_store.position[2]});
  add('occ_shelter', assets.shelter({ id: 'occ_shelter', open: true }), 'occluder', ${J(occ.occ_shelter.label)}, ${C(occ.occ_shelter.citation)}, false, ${occ.occ_shelter.position[0]}, ${occ.occ_shelter.position[2]});
  add('occ_pole', assets.pole({ id: 'occ_pole', height: 10 }), 'occluder', 'Utility pole broken by Vehicle A (position derived)', ${C('NTSB/HAR-17/02 p.1; ' + kd.pole_note)}, true, ${kd.pole_position_approx[0]}, ${kd.pole_position_approx[1]});

  // ---------- marks ----------
  add('mark_impact', assets.impactMarker({ id: 'mark_impact', position: [0, 0] }), 'mark', 'Initial point of impact (EB outside lane at NE 140th Ct)', 'NTSB/HAR-17/02 p.1, p.5', false, 0, 0);
  add('mark_rest_A', assets.impactMarker({ id: 'mark_rest_A', position: [${kd.car_rest_position_approx[0]}, ${kd.car_rest_position_approx[1]}] }), 'mark', 'Final rest of Vehicle A (~910 ft past impact)', ${C('NTSB/HAR-17/02 p.1; position approximate')}, false, ${kd.car_rest_position_approx[0]}, ${kd.car_rest_position_approx[1]});
  const KA = ${kf('veh_A')};
  const pathPts = KA.filter((k) => k[0] > ${c.timeline.t_impact}).map((k) => [k[1], k[2]]);
  const pathMark = assets.skidMark({ id: 'mark_path_A', points: pathPts, width: 0.3 });
  pathMark.name = 'mark_path_A'; root.add(pathMark);
  objects.mark_path_A = { node: pathMark, kind: 'mark', label: 'Post-impact path of Vehicle A (no pre-impact tire marks)', citation: 'NTSB/HAR-17/02 p.1, p.5', occludes: false };

  // ---------- vehicles (library assets; front = local -Z) ----------
  const A = add('veh_A', assets.vehicle('sedan', { id: 'veh_A', color: '#1d2c44' }), 'vehicle', ${J(veh.veh_A.label)}, ${C(veh.veh_A.citation)}, true).node;
  const TT = add('veh_T_tractor', assets.vehicle('truck_tractor', { id: 'veh_T_tractor', color: '#e8e8e8' }), 'vehicle', ${J(veh.veh_T_tractor.label)}, ${C(veh.veh_T_tractor.citation)}, true).node;
  const TR = add('veh_T_trailer', assets.vehicle('semitrailer', { id: 'veh_T_trailer', color: '#f2f2ee' }), 'vehicle', ${J(veh.veh_T_trailer.label)}, ${C(veh.veh_T_trailer.citation)}, true).node;

  // ---------- motion: linear interpolation of case.json keyframes [t, x, z, heading_deg] ----------
  const KT = ${kf('veh_T_tractor')};
  const KR = ${kf('veh_T_trailer')};
  function sample(K, t) {
    if (t <= K[0][0]) return K[0];
    const last = K[K.length - 1];
    if (t >= last[0]) return last;
    let i = 0;
    while (K[i + 1][0] < t) i++;
    const a = K[i], b = K[i + 1], u = (t - a[0]) / (b[0] - a[0]);
    let dh = b[3] - a[3];
    if (dh > 180) dh -= 360;
    if (dh < -180) dh += 360;
    return [t, a[1] + (b[1] - a[1]) * u, a[2] + (b[2] - a[2]) * u, a[3] + dh * u];
  }
  function place(node, K, t) {
    const s = sample(K, t);
    node.position.set(s[1], 0, s[2]);
    node.rotation.set(0, -s[3] * D2R, 0);
  }

  const T_IMPACT = ${c.timeline.t_impact};
  const duration = ${c.timeline.duration_s};
  function setTime(t) {
    t = Math.min(Math.max(t, 0), duration);
    place(A, KA, t);
    place(TT, KT, t);
    place(TR, KR, t);
    root.updateMatrixWorld(true);
  }

  // ---------- witnesses (FICTIONAL) ----------
  const witnesses = ${JSON.stringify(witnesses, null, 2).replace(/\n/g, '\n  ')};

  const facts = ${JSON.stringify(facts, null, 2).replace(/\n/g, '\n  ')};
  const skids = []; // ${c.skids_note}

  const world = {
    meta: { caseId: ${J(c.caseId)}, title: ${J(c.title)}, timeOfDay: ${J(c.timeOfDay)}, lighting: ${J(c.lighting)}, impactT: T_IMPACT,
      date: ${J(loc.date)}, timeZone: ${J(loc.timeZone)}, utcOffset: ${J(loc.utcOffset)}, lat: ${loc.lat}, lon: ${loc.lon},
      source: 'NTSB/HAR-17/02 (HWY16FH018) physical facts + fictional witnesses', contract: 'v2' },
    root, duration, setTime, objects, witnesses, facts, skids,
  };
  setTime(0);
  return world;
}
`;
fs.writeFileSync(path.join(here, 'reference_world.js'), src);
console.log('wrote worlds/reference_world.js', src.length, 'bytes');
