// Regenerates worlds/reference_world.js from case/case.json (keyframes, dims, witnesses, facts).
// Usage: node worlds/build_reference_world.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const c = JSON.parse(fs.readFileSync(path.join(here, '../case/case.json'), 'utf8'));
const veh = Object.fromEntries(c.vehicles.map((v) => [v.id, v]));
const kf = (id) => '[' + veh[id].keyframes.map((k) => `[${k.t},${k.x},${k.z},${k.heading_deg}]`).join(',') + ']';
const J = (o) => JSON.stringify(o);
const occ = Object.fromEntries(c.occluders.map((o) => [o.id, o]));
const kd = c.key_dimensions;

// Witness overrides (WORLD-slice geometry decisions; see status/world.md).
const witOverride = JSON.parse(fs.existsSync(path.join(here, 'witness_overrides.json')) ? fs.readFileSync(path.join(here, 'witness_overrides.json'), 'utf8') : '{}');
const witnesses = c.witnesses.map((w) => {
  const o = witOverride[w.id] || {};
  const p = o.position || w.marked_position || w.position;
  return {
    id: w.id, name: w.name, position: [p[0], 0, p[2]], eyeHeight: w.eyeHeight, lookAt: o.lookAt || w.lookAt,
    observationTime: o.observationTime ?? w.observationTime_s ?? w.observationTime, claim: w.claim, citation: w.citation,
    ...(o.note ? { note: o.note } : {}),
  };
});
const facts = [
  { id: 'f_impact_t', text: `Impact at t=${c.timeline.t_impact} s on the event clock (car crests the hill at t=0)`, value: c.timeline.t_impact, unit: 's', citation: 'NTSB/HAR-17/02 p.22, p.29 (derived from 74 mph over 345 m)', kind: 'time' },
  ...c.facts,
];

const src = `// Sightline reference world: ${c.title}
// GENERATED by worlds/build_reference_world.mjs from case/case.json, then usable stand-alone. Follows THE WORLD CONTRACT (SPEC.md).
// ${c.source_note}
// Frame: meters, Y up, +X east (direction of Vehicle A), -Z north. Origin = initial point of impact (center of EB outside lane at NE 140th Ct).
// Ground is modeled flat (case.coordinate_frame_note allows this; the 2.15% grade does not affect witness sightlines).
export default function createWorld(THREE) {
  const root = new THREE.Group();
  root.name = 'world_root';
  const objects = {};
  const D2R = Math.PI / 180;

  // ---------- helpers ----------
  const mat = (color, extra = {}) => new THREE.MeshStandardMaterial({ color, roughness: 0.85, ...extra });
  function box(w, h, d, color, x = 0, y = 0, z = 0) {
    const m = new THREE.Mesh(new THREE.BoxGeometry(w, h, d), typeof color === 'number' ? mat(color) : color);
    m.position.set(x, y, z);
    return m;
  }
  // flat rectangle on the ground spanning x0..x1, z0..z1
  function rect(x0, x1, z0, z1, color, y = 0.02) {
    const m = new THREE.Mesh(new THREE.PlaneGeometry(x1 - x0, z1 - z0), mat(color));
    m.rotation.x = -Math.PI / 2;
    m.position.set((x0 + x1) / 2, y, (z0 + z1) / 2);
    return m;
  }
  function add(id, node, info) {
    node.name = id;
    root.add(node);
    objects[id] = { node, ...info };
    return node;
  }

  // ---------- lighting: 16:36 EDT, clear; sun high and behind (west of) the eastbound car ----------
  const hemi = new THREE.HemisphereLight(0xdfe9ff, 0x5a5a40, 0.85);
  hemi.name = 'light_hemi';
  root.add(hemi);
  const sun = new THREE.DirectionalLight(0xfff4e0, 1.7);
  sun.name = 'light_sun';
  sun.position.set(-70, 85, 25);
  root.add(sun);

  // ---------- ground and roadway (US-27A, four-lane divided, 3.66 m lanes) ----------
  const X0 = -440, X1 = 340;
  root.add(Object.assign(rect(X0, X1, -160, 160, 0x6f7f4f, 0), { name: 'ground' }));
  const ASPH = 0x3b3b3d, WHITE = 0xf4f4f4, YEL = 0xf2c200;

  const eb = new THREE.Group();
  eb.add(rect(X0, X1, -6.1, 3.35, ASPH));                                    // EB lanes + shoulders
  eb.add(rect(X0, X1, ${kd.eb_right_shoulder_z[0]} - 0.08, ${kd.eb_right_shoulder_z[0]} + 0.08, WHITE, 0.03)); // right edge line
  eb.add(rect(X0, X1, ${kd.eb_inside_lane_z[0]} - 0.08, ${kd.eb_inside_lane_z[0]} + 0.08, YEL, 0.03));   // left (median) edge line
  for (let x = X0; x < X1; x += 12.2) eb.add(rect(x, x + 3.05, -1.91, -1.75, WHITE, 0.03)); // lane line (10 ft dash / 30 ft gap)
  add('road_eb', eb, { kind: 'road', label: 'US-27A eastbound (2 x 3.66 m lanes, 65 mph limit)', citation: 'NTSB/HAR-17/02 p.22-23', occludes: false });

  const wb = new THREE.Group();
  wb.add(rect(X0, X1, ${kd.wb_right_shoulder_z[0]}, ${kd.wb_inside_lane_z[1]} + 0.6, ASPH));                   // WB lanes + shoulders
  wb.add(rect(-19.8, 167.6, ${kd.wb_left_turn_lane_z[0]}, ${kd.wb_left_turn_lane_z[1]}, ASPH, 0.021));   // WB left-turn lane (167.6 m)
  wb.add(rect(X0, X1, ${kd.wb_outside_lane_z[0]} - 0.08, ${kd.wb_outside_lane_z[0]} + 0.08, WHITE, 0.03));
  for (let x = X0; x < X1; x += 12.2) wb.add(rect(x, x + 3.05, -33.0, -32.84, WHITE, 0.03));
  wb.add(rect(-19.8, 167.6, -29.34, -29.18, WHITE, 0.031));
  add('road_wb', wb, { kind: 'road', label: 'US-27A westbound with left-turn lane', citation: 'NTSB/HAR-17/02 p.22', occludes: false });

  const med = new THREE.Group();
  med.add(rect(X0, -19.8, ${kd.median_z[0]}, ${kd.median_z[1]}, 0x5f7a3c, 0.015));
  med.add(rect(19.8, X1, ${kd.median_z[0]}, ${kd.median_z[1]}, 0x5f7a3c, 0.015));
  med.add(rect(-19.8, 19.8, -25.6, -6.1, ASPH, 0.02));                         // paved crossover (39.6 m)
  add('road_crossover', med, { kind: 'road', label: 'Median (18.29 m) with uncontrolled 39.6 m crossover', citation: 'NTSB/HAR-17/02 p.22', occludes: false });

  const side = new THREE.Group();
  side.add(rect(${kd.side_road.x_range[0]}, ${kd.side_road.x_range[1]}, 3.35, 150, 0x47474a));
  add('road_ne140', side, { kind: 'road', label: 'NE 140th Court (runs south; 109 deg skew simplified)', citation: 'NTSB/HAR-17/02 p.1, p.22; width assumed', occludes: false });

  // ---------- static occluders / scenery ----------
  // Vertical crest 345 m west: modeled as the hill mass beyond the crest (road kept flat), so the car "appears" over it at t=0.
  const crest = box(60, 7.4, 80, 0x6a7a48, ${kd.crest_x_m} - 32, 3.7, -15);
  add('occ_crest', crest, { kind: 'occluder', label: 'Vertical crest of US-27A, 1,132 ft (345 m) west (only sight restriction)', citation: ${J(occ.occ_crest.citation)}, occludes: true });

  const store = new THREE.Group();
  store.add(box(18, ${occ.bld_store.height}, 12, 0xa69a86, 0, ${occ.bld_store.height / 2}, 0));
  store.add(box(18.4, 0.3, 12.4, 0x7a6e5e, 0, ${occ.bld_store.height} + 0.15, 0));
  store.position.set(${occ.bld_store.position[0]}, 0, ${occ.bld_store.position[2]});
  add('bld_store', store, { kind: 'building', label: ${J(occ.bld_store.label)}, citation: ${J(occ.bld_store.citation)}, occludes: true });

  // Open-sided bench shelter: roof + thin posts only. Does NOT block a standing eye line (occludes:false per case.json).
  const shelter = new THREE.Group();
  shelter.add(box(3.0, 0.12, 1.8, 0x445566, 0, 2.6, 0));
  for (const [px, pz] of [[-1.45, -0.85], [1.45, -0.85], [-1.45, 0.85], [1.45, 0.85]]) shelter.add(box(0.1, 2.6, 0.1, 0x666666, px, 1.3, pz));
  shelter.add(box(2.6, 0.45, 0.45, 0x8b6b4a, 0, 0.45, 0.5));  // bench
  shelter.position.set(${occ.occ_shelter.position[0]}, 0, ${occ.occ_shelter.position[2]});
  add('occ_shelter', shelter, { kind: 'occluder', label: ${J(occ.occ_shelter.label)}, citation: ${J(occ.occ_shelter.citation)}, occludes: false });

  const pole = new THREE.Mesh(new THREE.CylinderGeometry(0.15, 0.18, 10, 10), mat(0x6b4f33));
  pole.position.set(${kd.pole_position_approx[0]}, 5, ${kd.pole_position_approx[1]});
  add('occ_pole', pole, { kind: 'occluder', label: 'Utility pole broken by Vehicle A (position derived)', citation: 'NTSB/HAR-17/02 p.1; ' + ${J(kd.pole_note)}, occludes: true });

  // ---------- marks ----------
  const poi = new THREE.Mesh(new THREE.CylinderGeometry(0.7, 0.7, 0.02, 24), mat(0xff00ff));
  poi.position.set(0, 0.045, 0);
  add('mark_impact', poi, { kind: 'mark', label: 'Initial point of impact (EB outside lane at NE 140th Ct)', citation: 'NTSB/HAR-17/02 p.1, p.5', occludes: false });
  const rest = new THREE.Mesh(new THREE.CylinderGeometry(1.2, 1.2, 0.02, 24), mat(0xffaa00));
  rest.position.set(${kd.car_rest_position_approx[0]}, 0.045, ${kd.car_rest_position_approx[1]});
  add('mark_rest_A', rest, { kind: 'mark', label: 'Final rest of Vehicle A (~910 ft past impact)', citation: 'NTSB/HAR-17/02 p.1', occludes: false });
  const path = new THREE.Group();     // post-impact travel path (dots), no tire marks pre-impact
  const KA = ${kf('veh_A')};
  for (const k of KA) if (k[0] > ${c.timeline.t_impact} && Math.round(k[0] * 4) % 2 === 0) path.add(rect(k[1] - 0.3, k[1] + 0.3, k[2] - 0.3, k[2] + 0.3, 0x9a8a60, 0.04));
  add('mark_path_A', path, { kind: 'mark', label: 'Post-impact path of Vehicle A (no pre-impact tire marks)', citation: 'NTSB/HAR-17/02 p.1, p.5', occludes: false });

  // ---------- vehicles (front = local -Z; rotation.y = -heading) ----------
  // Vehicle A: passenger car (sedan), 4.97 x 1.96 x 1.445 m, hood rear 0.91 m.
  const A = new THREE.Group();
  A.add(box(1.96, 0.66, 4.97, 0x1d2c44, 0, 0.25 + 0.33, 0));                // body to hood height 0.91
  const cabin = box(1.8, 0.535, 2.3, 0x24344f, 0, 0.91 + 0.2675, 0.25);     // greenhouse (sheared at impact)
  cabin.name = 'veh_A_cabin';
  A.add(cabin);
  for (const [wx, wz] of [[-0.9, -1.5], [0.9, -1.5], [-0.9, 1.5], [0.9, 1.5]]) A.add(box(0.25, 0.6, 0.6, 0x111111, wx, 0.3, wz));
  add('veh_A', A, { kind: 'vehicle', label: ${J(veh.veh_A.label)}, citation: ${J(veh.veh_A.citation)}, occludes: true });

  // Truck-tractor: 6.6 x 2.5 x 4.0 m (cab + sleeper forward, chassis/fifth wheel aft).
  const TT = new THREE.Group();
  TT.add(box(2.5, 3.7, 3.4, 0xd8d8d8, 0, 0.3 + 1.85, -1.6));                // cab + sleeper (front 3.4 m)
  TT.add(box(2.5, 1.2, 3.2, 0x333333, 0, 0.3 + 0.6, 1.7));                   // chassis, tanks, fifth wheel
  for (const wz of [-2.6, 1.0, 2.4]) for (const wx of [-1.1, 1.1]) TT.add(box(0.35, 1.0, 1.0, 0x111111, wx, 0.5, wz));
  add('veh_T_tractor', TT, { kind: 'vehicle', label: ${J(veh.veh_T_tractor.label)}, citation: ${J(veh.veh_T_tractor.citation)}, occludes: true });

  // Semitrailer: 16.15 x 2.59 m box, bed 1.2 m to 4.11 m; tandem axles at the rear.
  const TR = new THREE.Group();
  TR.add(box(2.59, 2.91, 16.15, 0xf2f2ee, 0, 1.2 + 1.455, 0));
  for (const wz of [5.6, 6.9]) for (const wx of [-1.0, 1.0]) TR.add(box(0.5, 1.0, 1.0, 0x111111, wx, 0.5, wz));
  for (const wx of [-0.9, 0.9]) TR.add(box(0.15, 1.2, 0.15, 0x555555, wx, 0.6, -4.5));   // landing gear
  add('veh_T_trailer', TR, { kind: 'vehicle', label: ${J(veh.veh_T_trailer.label)}, citation: ${J(veh.veh_T_trailer.citation)}, occludes: true });

  // ---------- motion: linear interpolation of case.json keyframes [t, x, z, heading_deg] ----------
  const KT = ${kf('veh_T_tractor')};
  const KR = ${kf('veh_T_trailer')};
  function sample(K, t) {
    if (t <= K[0][0]) return K[0];
    const last = K[K.length - 1];
    if (t >= last[0]) return last;
    let i = 0;
    while (K[i + 1][0] < t) i++;
    const a = K[i], b = K[i + 1], u = (t - a[0]) / (b[0] - a[0]);
    let dh = b[3] - a[3];
    if (dh > 180) dh -= 360;
    if (dh < -180) dh += 360;
    return [t, a[1] + (b[1] - a[1]) * u, a[2] + (b[2] - a[2]) * u, a[3] + dh * u];
  }
  function place(node, K, t) {
    const s = sample(K, t);
    node.position.set(s[1], 0, s[2]);
    node.rotation.set(0, -s[3] * D2R, 0);
  }

  const T_IMPACT = ${c.timeline.t_impact};
  const duration = ${c.timeline.duration_s};
  function setTime(t) {
    t = Math.min(Math.max(t, 0), duration);
    place(A, KA, t);
    place(TT, KT, t);
    place(TR, KR, t);
    cabin.visible = t < T_IMPACT;   // roof sheared as the car passes under the trailer
    root.updateMatrixWorld(true);
  }

  // ---------- witnesses (FICTIONAL) ----------
  const witnesses = ${JSON.stringify(witnesses, null, 2).replace(/\n/g, '\n  ')};

  const facts = ${JSON.stringify(facts, null, 2).replace(/\n/g, '\n  ')};
  const skids = []; // ${c.skids_note}

  const world = {
    meta: { caseId: ${J(c.caseId)}, title: ${J(c.title)}, timeOfDay: ${J(c.timeOfDay)}, lighting: ${J(c.lighting)},
      source: 'NTSB/HAR-17/02 (HWY16FH018) physical facts + fictional witnesses' },
    root, duration, setTime, objects, witnesses, facts, skids,
  };
  setTime(0);
  return world;
}
`;
fs.writeFileSync(path.join(here, 'reference_world.js'), src);
console.log('wrote worlds/reference_world.js', src.length, 'bytes');
